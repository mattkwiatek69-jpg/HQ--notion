/* Writes health-hub/DOCS-AUDIT.md: every section of OP 1 and OP 2, and where the hub uses it.
   Run after changing data/docrefs.js or rebuilding the docs index: node health-hub/tools/docs-audit.js */
const fs = require("fs"), path = require("path");
global.window = { PHH: {} };
const D = path.join(__dirname, "../data");
["routines-a", "routines-b", "systems", "sources", "nutrition", "products", "today", "meta", "schedule", "guide", "areas", "docindex", "docrefs"].forEach((f) => require(path.join(D, f + ".js")));
const P = window.PHH, by = {};
const name = (ref) => {
  const [k, id] = [ref[0], ref.slice(2)];
  if (k === "r") return "Routine: " + ((P.routines.find((r) => r.id === id) || {}).name || id);
  if (k === "t") return "Topic: " + ((P.systems.concat(P.extras).find((t) => t.id === id) || {}).name || id);
  if (k === "i") { if (id === "habits") return "Daily: all-day habits"; let t = id; P.blocks.forEach((b) => b.items.forEach((i) => { if (i.id === id) t = i.t; })); return "Daily: " + t; }
  if (k === "n") return "Nutrition (" + (id === "op" ? "OP docs hub" : "Mine hub") + ")";
  if (k === "p") return "Products (" + (id === "op" ? "OP docs hub" : "Mine hub") + ")";
  return "The plan as a whole";
};
Object.keys(P.docRefs).forEach((ref) => P.docRefs[ref].forEach((id) => (by[id] = by[id] || []).push(name(ref))));
const op = P.docs.filter((d) => d.src === "op"), all = op.reduce((a, d) => a + d.secs.length, 0), linked = op.reduce((a, d) => a + d.secs.filter((x) => by[x.id]).length, 0);
const daily = []; P.blocks.forEach((b) => b.items.forEach((i) => { if (i.k) daily.push([b.name, i]); }));
let md = `# OP docs audit

Generated by \`health-hub/tools/docs-audit.js\` from the hub's own data, so it stays true to it.

## Summary

- **${all} sections** in OP 1 and OP 2 (images left out: the Drive export is text only). **${linked} of ${all}** are linked from at least one routine, topic, daily item, Nutrition or Products, and \`tests/data.test.js\` fails if one stops being linked.
- **Every section** is listed in the hub (Library › The docs, Find, and "In the docs" on every record that uses it), and opens at its place in Google Docs. The structured records (routines, topics, daily items) are summaries of what to do; the reasoning, mechanisms and background are in the docs, word for word.
- The **full text** can also be read inside the hub and searched by Find, from \`data/docs-text.js\` (built by \`tools/build-docs.py\`). It is **not in git**, because the repository is public and the OP docs are a paid programme, and it is **not on the published page yet**, because that page is shared with anyone with the link. It goes there only if the owner asks.
- **${daily.length} daily items** (not a routine or gym): ${P.dailyGroups.map((g) => `${daily.filter((x) => x[1].k === g[0]).length} ${g[1].toLowerCase()}`).join(", ")}. Six were missing before this audit and were added from the docs: Spring water in glass, Celtic sea salt, Calcium 1 g a day, Raw milk and honey late, Bed only for sleep, A firmer surface.

## Daily items

| Part of the day | Item | Kind | Source | In the docs |
|---|---|---|---|---|
${daily.map(([b, i]) => `| ${b} | ${i.t}${i.opt ? " (optional)" : ""} | ${(P.dailyGroups.find((g) => g[0] === i.k) || [])[1]} | ${i.src === "both" ? "OP docs + Max doc" : "OP docs"} | ${(P.docRefs["i:" + i.id] || []).map((id) => { const d = op.find((x) => x.secs.some((y) => y.id === id)); return d ? d.n + " › " + d.secs.find((y) => y.id === id).h : id; }).join("; ")} |`).join("\n")}

## Every OP section and where the hub uses it
`;
op.forEach((d) => {
  md += `\n### ${d.n}\n\n| Chapter | Section | Used by |\n|---|---|---|\n`;
  d.secs.forEach((x) => { md += `| ${x.ch || ""}${x.g ? " › " + x.g : ""} | ${x.h} | ${(by[x.id] || ["not linked"]).join("; ")} |\n`; });
});
fs.writeFileSync(path.join(__dirname, "../DOCS-AUDIT.md"), md);
console.log("DOCS-AUDIT.md:", linked + "/" + all, "sections linked,", daily.length, "daily items");
